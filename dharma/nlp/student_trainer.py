# Main
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(
        description="D.H.A.R.M.A. DistilBERT Student Model Trainer"
    )
    parser.add_argument(
        "--seed-file",
        default=DEFAULT_SEED_FILE,
        help="Path to the Gold Seed JSON file",
    )
    parser.add_argument(
        "--model-dir",
        default=DEFAULT_MODEL_DIR,
        help="Directory to save fine-tuned model",
    )
    parser.add_argument("--epochs", type=int, default=NUM_EPOCHS)
    parser.add_argument("--batch-size", type=int, default=BATCH_SIZE)
    parser.add_argument("--lr", type=float, default=LEARNING_RATE)
    parser.add_argument("--confidence-threshold", type=float, default=CONFIDENCE_THRESHOLD)
    parser.add_argument("--dropout", type=float, default=0.3, help="Dropout rate for classification heads and backbone")
    parser.add_argument("--noise-std", type=float, default=0.05, help="Standard deviation of Gaussian noise during training for realistic validation generalization")
    args = parser.parse_args()

    start_time = time.time()
    device = torch.device("cpu")

    logger.info("=" * 70)
    logger.info("D.H.A.R.M.A. — DistilBERT Student Model Training")
    logger.info("=" * 70)
    logger.info("Device: %s (threads=%d)", device, torch.get_num_threads())
    logger.info("Seed file: %s", args.seed_file)
    logger.info("Model output: %s", args.model_dir)
    logger.info(
        "Hyperparams: lr=%.0e, batch=%d, epochs=%d, weight_decay=%.3f",
        args.lr, args.batch_size, args.epochs, WEIGHT_DECAY,
    )

    # ── Step 1: Load and filter data ──
    if not os.path.exists(args.seed_file):
        logger.error("Seed file not found: %s", args.seed_file)
        sys.exit(1)

    texts, labels = load_and_filter_gold_seeds(
        args.seed_file,
        confidence_threshold=args.confidence_threshold,
    )

    if len(texts) < 10:
        logger.error(
            "Insufficient training data after filtering: %d records. "
            "Need at least 10. Lower the confidence threshold or "
            "generate more seed data.",
            len(texts),
        )
        sys.exit(1)

    # ── Step 2: Train/Val split ──
    np.random.seed(RANDOM_SEED)
    torch.manual_seed(RANDOM_SEED)

    val_size = max(0.15, min(0.25, 50 / len(texts)))  # At least 15%, adaptive
    train_indices, val_indices = train_test_split(
        list(range(len(texts))),
        test_size=val_size,
        random_state=RANDOM_SEED,
    )

    train_texts = [texts[i] for i in train_indices]
    val_texts = [texts[i] for i in val_indices]
    train_labels = {head: [labels[head][i] for i in train_indices] for head in LABEL_MAPS}
    val_labels = {head: [labels[head][i] for i in val_indices] for head in LABEL_MAPS}

    logger.info(
        "Data split: %d train, %d validation (%.1f%% val)",
        len(train_texts), len(val_texts), val_size * 100,
    )

    # Log label distributions
    for head_name in LABEL_MAPS:
        label_names = list(LABEL_MAPS[head_name].keys())
        from collections import Counter
        dist = Counter(train_labels[head_name])
        dist_str = ", ".join(
            f"{label_names[k]}={v}" for k, v in sorted(dist.items())
        )
        logger.info("  %s distribution: %s", head_name, dist_str)

    # ── Step 3: Tokenizer & Datasets ──
    logger.info("Loading DistilBERT tokenizer...")
    tokenizer = DistilBertTokenizer.from_pretrained("distilbert-base-uncased")

    train_dataset = MODataset(train_texts, train_labels, tokenizer, MAX_SEQ_LENGTH)
    val_dataset = MODataset(val_texts, val_labels, tokenizer, MAX_SEQ_LENGTH)

    train_loader = DataLoader(
        train_dataset,
        batch_size=args.batch_size,
        shuffle=True,
        num_workers=4,
        pin_memory=False,
    )
    val_loader = DataLoader(
        val_dataset,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=2,
        pin_memory=False,
    )

    # ── Step 4: Model ──
    logger.info("Initializing MultiHeadDistilBERT model (dropout=%.2f, noise_std=%.3f)...", args.dropout, args.noise_std)
    model = MultiHeadDistilBERT(NUM_CLASSES, dropout=args.dropout, noise_std=args.noise_std).to(device)

    total_params = sum(p.numel() for p in model.parameters())
    trainable_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    logger.info(
        "Model: %s total params, %s trainable",
        f"{total_params:,}", f"{trainable_params:,}",
    )

    # ── Step 5: Optimizer & Scheduler ──
    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=args.lr,
        weight_decay=WEIGHT_DECAY,
    )

    total_steps = len(train_loader) * args.epochs
    warmup_steps = int(total_steps * WARMUP_RATIO)
    scheduler = get_linear_schedule_with_warmup(
        optimizer,
        num_warmup_steps=warmup_steps,
        num_training_steps=total_steps,
    )

    logger.info(
        "Scheduler: %d total steps, %d warmup steps",
        total_steps, warmup_steps,
    )

    # ── Step 6: Training Loop ──
    best_val_loss = float("inf")
    training_log = []

    logger.info("\n" + "=" * 70)
    logger.info("STARTING TRAINING")
    logger.info("=" * 70)

    for epoch in range(1, args.epochs + 1):
        epoch_start = time.time()

        logger.info("\n--- Epoch %d/%d ---", epoch, args.epochs)

        train_loss = train_epoch(model, train_loader, optimizer, scheduler, device)
        val_loss, val_metrics = evaluate(model, val_loader, device)

        epoch_time = time.time() - epoch_start

        # Log per-head accuracy
        accs = {head: val_metrics[head]["accuracy"] for head in LABEL_MAPS}
        avg_acc = np.mean(list(accs.values()))

        logger.info(
            "Epoch %d complete in %.1fs — "
            "train_loss=%.4f, val_loss=%.4f, avg_acc=%.4f",
            epoch, epoch_time, train_loss, val_loss, avg_acc,
        )
        for head, acc in accs.items():
            logger.info("  %s accuracy: %.4f", head, acc)

        training_log.append({
            "epoch": epoch,
            "train_loss": round(train_loss, 4),
            "val_loss": round(val_loss, 4),
            "avg_accuracy": round(avg_acc, 4),
            "per_head_accuracy": {h: round(a, 4) for h, a in accs.items()},
            "epoch_time_seconds": round(epoch_time, 1),
        })

        # Save best model
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            logger.info("  ★ New best val_loss=%.4f — saving checkpoint", val_loss)
            os.makedirs(args.model_dir, exist_ok=True)
            torch.save(model.state_dict(), os.path.join(args.model_dir, "model.pt"))

    # ── Step 7: Save tokenizer, config, and training log ──
    logger.info("\nSaving tokenizer and metadata...")
    tokenizer.save_pretrained(args.model_dir)

    # Save label maps and config
    config = {
        "model_type": "MultiHeadDistilBERT",
        "base_model": "distilbert-base-uncased",
        "max_seq_length": MAX_SEQ_LENGTH,
        "num_classes": NUM_CLASSES,
        "label_maps": LABEL_MAPS,
        "inverse_label_maps": {
            head: {v: k for k, v in lm.items()} for head, lm in LABEL_MAPS.items()
        },
        "confidence_threshold": args.confidence_threshold,
        "training_hyperparameters": {
            "learning_rate": args.lr,
            "batch_size": args.batch_size,
            "num_epochs": args.epochs,
            "weight_decay": WEIGHT_DECAY,
            "warmup_ratio": WARMUP_RATIO,
        },
    }

    with open(os.path.join(args.model_dir, "config.json"), "w") as f:
        json.dump(config, f, indent=2)

    with open(os.path.join(args.model_dir, "training_log.json"), "w") as f:
        json.dump(training_log, f, indent=2)

    # ── Step 8: Final Evaluation Report ──
    logger.info("\n" + "=" * 70)
    logger.info("FINAL EVALUATION REPORT")
    logger.info("=" * 70)

    # Reload best model for final eval
    model.load_state_dict(torch.load(os.path.join(args.model_dir, "model.pt"),
                                     map_location=device, weights_only=True))
    _, final_metrics = evaluate(model, val_loader, device)

    label_name_maps = {
        "weapon_classification": WEAPON_LABELS,
        "point_of_entry": ENTRY_LABELS,
        "target_profile": TARGET_LABELS,
        "suspect_count_estimate": SUSPECT_LABELS,
    }

    for head_name in LABEL_MAPS:
        metrics = final_metrics[head_name]
        logger.info("\n── %s (accuracy: %.4f) ──", head_name, metrics["accuracy"])
        report = metrics["report"]
        for class_name, values in report.items():
            if isinstance(values, dict) and "precision" in values:
                logger.info(
                    "  %-20s  P=%.2f  R=%.2f  F1=%.2f  N=%d",
                    class_name,
                    values["precision"],
                    values["recall"],
                    values["f1-score"],
                    int(values["support"]),
                )

    total_time = time.time() - start_time
    logger.info("\n" + "=" * 70)
    logger.info("TRAINING COMPLETE")
    logger.info("Total time: %.1f seconds (%.1f minutes)", total_time, total_time / 60)
    logger.info("Model saved to: %s", args.model_dir)
    logger.info("=" * 70)


if __name__ == "__main__":
    main()
